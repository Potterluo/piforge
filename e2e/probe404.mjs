import { chromium } from "@playwright/test";
const browser = await chromium.launch({ channel: "chrome", headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
page.on("pageerror", (e) => console.log("JS", e.message.slice(0, 200)));
await page.goto("http://127.0.0.1:7722/login");
await page.getByTestId("login-email").fill("dev@piforge.local");
await page.getByTestId("login-password").fill("piforge-dev-123");
await page.getByTestId("login-submit").click();
await page.getByTestId("app-sidebar").waitFor({ timeout: 20000 });
await page.waitForTimeout(1000);
await page.getByTestId("account-menu").click();
await page.waitForTimeout(300);
console.log("ACCOUNT", await page.getByTestId("account-panel").innerText());
await page.getByTestId("account-panel").getByText("设置").click();
await page.waitForTimeout(1500);
console.log("SETTINGS-URL", page.url());
// the three panels' key controls
await page.goto("http://127.0.0.1:7722/");
await page.waitForTimeout(800);
console.log("HOME-OK", await page.getByTestId("app-sidebar").isVisible());
await browser.close();