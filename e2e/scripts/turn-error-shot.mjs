import { chromium } from "@playwright/test";
import path from "node:path";
const BASE = process.env.BASE;
const SID = process.env.SID;
const browser = await chromium.launch({ channel: "chrome" });
const page = await browser.newPage({ viewport: { width: 1440, height: 900 }, deviceScaleFactor: 2 });
await page.goto(`${BASE}/login`);
await page.getByTestId("login-email").fill("dev@piforge.local");
await page.getByTestId("login-password").fill("piforge-dev-123");
await page.getByTestId("login-submit").click();
await page.getByTestId("app-sidebar").waitFor({ timeout: 30000 });
const listed = await (await page.request.get(`${BASE}/v1/projects`)).json();
const project = listed.projects.find((p) => p.name === "no-provider");
await page.goto(`${BASE}/p/${project.id}/s/${SID}`);
await page.waitForTimeout(3000);
await page.screenshot({ path: path.resolve("../docs/screenshots/31-turn-error.png") });
const alerts = await page.locator("[data-testid='turn-error']").allTextContents();
console.log("alerts:", JSON.stringify(alerts));
console.log("empty bubbles:", await page.locator("[data-testid='turn-assistant']").count());
await browser.close();
