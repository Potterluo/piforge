import { chromium } from "@playwright/test";
import path from "node:path";
const BASE = "http://127.0.0.1:7722";
const OUT = path.resolve("../docs/screenshots");
const SID = process.env.SID;
const browser = await chromium.launch({ channel: "chrome" });
const page = await browser.newPage({ viewport: { width: 1440, height: 900 }, deviceScaleFactor: 2 });
await page.goto(`${BASE}/login`);
await page.getByTestId("login-email").fill("admin@piforge.local");
await page.getByTestId("login-password").fill("piforge-admin-123");
await page.getByTestId("login-submit").click();
await page.getByTestId("app-sidebar").waitFor({ timeout: 30000 });
await page.goto(`${BASE}/admin/support`);
await page.getByTestId("support-session").fill(SID);
await page.getByTestId("support-reason").fill("用户报告 run 卡住，查看最后一次工具调用");
await page.getByTestId("support-submit").click();
await page.getByTestId("support-transcript").waitFor({ timeout: 30000 });
await page.waitForTimeout(800);
await page.screenshot({ path: path.join(OUT, "56-support-mode.png") });
console.log("ok");
await browser.close();